test("composition pins its first executable before applying the isolated environment", async () => {
  const out = await realpath(await mkdtemp(join(tmpdir(), "compose-path-")));
  try {
    const marker = join(out, "unexpected-executable");
    await writeFile(
      join(out, "env"),
      '#!/bin/sh\nprintf invoked > "$C6_PROBE_MARKER"\nexec /usr/bin/env "$@"\n',
      { mode: 0o700 },
    );
    const probe = Bun.spawn(
      [
        process.execPath,
        "-e",
        "import { compositionGit } from './tools/migration/compose-target'; await compositionGit(process.cwd(), 'rev-parse', '--is-inside-work-tree');",
      ],
      {
        cwd: join(import.meta.dir, "../.."),
        env: { ...process.env, PATH: `${out}:/usr/bin:/bin`, C6_PROBE_MARKER: marker },
        stdout: "ignore",
        stderr: "ignore",
      },
    );
    expect(await probe.exited).toBe(0);
    expect(await Bun.file(marker).exists()).toBe(false);
  } finally {
    await rm(out, { recursive: true, force: true });
  }
});
