test("CLI requires independently pinned policy and emits opaque composition evidence", async () => {
  const { writeFile } = await import("node:fs/promises");
  const { sha } = await import("./fixtures/composition/fixture");
  const f = await fixture();
  const out = await realpath(await mkdtemp(join(tmpdir(), "compose-cli-")));
  try {
    const input = join(out, "input.json");
    const policy = join(out, "policy.json");
    const bytes = JSON.stringify(f.policy);
    await writeFile(input, JSON.stringify(f.input));
    await writeFile(policy, bytes);
    const child = Bun.spawn(
      [
        process.execPath,
        join(import.meta.dir, "compose-target.ts"),
        "--input",
        input,
        "--policy",
        policy,
        "--policy-sha256",
        sha(bytes),
        "--output",
        join(out, "run"),
      ],
      { stdout: "pipe", stderr: "pipe" },
    );
    const [stdout, stderr, exit] = await Promise.all([
      new Response(child.stdout).text(),
      new Response(child.stderr).text(),
      child.exited,
    ]);
    expect(exit).toBe(0);
    expect(stderr).toBe("");
    expect(JSON.parse(stdout).treeDigest).toMatch(/^[a-f0-9]{64}$/);
    expect(stdout).not.toContain(f.root);
    expect(await Bun.file(join(out, "run", "db-inspect", "main.bin")).exists()).toBe(true);
  } finally {
    await rm(f.root, { recursive: true, force: true });
    await rm(out, { recursive: true, force: true });
  }
});

